import assert from 'node:assert/strict';
import fs from 'node:fs';
const output='Documentacoes/.pages-output/';
const index=JSON.parse(fs.readFileSync(output+'knowledge/index.json','utf8'));
const helper=index.documentos.find(d=>d.unit==='TDD_MAPEAMENTO_EVENTOS');
const application=index.documentos.find(d=>d.unit==='P39_TDD_RUN_APPLICATION');
assert.ok(helper&&application);
assert.equal(helper.navegacao.grupo,'helpers');assert.equal(helper.navegacao.subgrupo,'gerais');
assert.equal(helper.tipoArtefato,'processamento');
for(const d of [helper,application])assert.equal(d.estado,'em-desenvolvimento');
for(const symbol of ['Main','ListarFormsAbertos','PegarConfiguracoesForm','FFormsAntes','FCaptionMenu'])assert.ok(helper.simbolos.some(s=>s.nome===symbol));
for(const symbol of ['AbrirTela','FocarModulo','TrazerParaFrente'])assert.ok(application.simbolos.some(s=>s.nome===symbol));
assert.ok(application.aliases.includes('TDD_RUN_MODULO'));
const canonical='docs/assets/snippets/TDD_MAPEAMENTO_EVENTOS.pas';
assert.deepEqual(fs.readFileSync(output+canonical),fs.readFileSync(canonical));
const markdown=fs.readFileSync(output+'knowledge/units/tdd-mapeamento-eventos.md','utf8');
assert.ok(markdown.includes(fs.readFileSync(canonical,'utf8')));
for(const phrase of ['cComponenteMenu','RichEdit1','múltiplas','não homologadas','não publica'])assert.ok(markdown.includes(phrase),phrase);
const redirect=fs.readFileSync('Documentacoes/app/catalogo/redirecionamentos.ts','utf8');
assert.match(redirect,/"\/units\/p39-tdd-run-modulo":\s*"\/units\/p39-tdd-run-application"/);
const helperSlice=fs.readFileSync('Documentacoes/app/components/helpers/gerais/index.ts','utf8');
assert.match(helperSlice,/mapeamentoEventos/);
console.log('APP-12 PASS independente: catálogo, navegação, estados, símbolos, redirect e snippet canônico publicado/copíavel. Sem browser ou homologação ERP.');
