SET NAMES UTF8;
SET AUTODDL OFF;

ALTER TABLE CASO_TESTE ADD REQUISITO_VERSAO_CT VARCHAR(10) CHARACTER SET UTF8;

CREATE TABLE HISTORICO_EXECUCAO (
  AUTOINC_HISTORICO_HE  INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  AUTOINC_CASO_TESTE_HE BIGINT NOT NULL,
  VERSAO_EXECUCAO_HE    VARCHAR(10) CHARACTER SET UTF8,
  REQUISITO_VERSAO_HE   VARCHAR(10) CHARACTER SET UTF8,
  STATUS_EXECUCAO_HE    VARCHAR(20) CHARACTER SET UTF8 NOT NULL,
  ETAPA_FALHA_HE        INTEGER,
  MENSAGEM_ERRO_HE      BLOB SUB_TYPE 1 SEGMENT SIZE 100 CHARACTER SET UTF8,
  LOGS_FALHAS_HE        BLOB SUB_TYPE 1 SEGMENT SIZE 100 CHARACTER SET UTF8,
  DATA_HORA_EXECUCAO_HE TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_HISTORICO_EXECUCAO_TESTE PRIMARY KEY (AUTOINC_HISTORICO_HE),
  CONSTRAINT CK_HISTORICO_EXECUCAO_STATUS CHECK (
    STATUS_EXECUCAO_HE IN ('SUCESSO', 'FALHA', 'ERROS', 'INCOMPATIVEL_VERSAO')
  ),
  CONSTRAINT FK_HISTORICO_EXECUCAO_CASO FOREIGN KEY (AUTOINC_CASO_TESTE_HE)
    REFERENCES CASO_TESTE (AUTOINC_CT)
);

CREATE TABLE METRICAS_TICK_DIFF (
  AUTOINC_METRICA_TICK_DIFF_TD INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  AUTOINC_HISTORICO_HE         INTEGER NOT NULL,
  NOME_METODO_TD               VARCHAR(120) CHARACTER SET UTF8,
  ETAPA_CASO_TESTE_TD          INTEGER,
  TEMPO_INICIO_TD              INTEGER,
  TEMPO_FIM_TD                 INTEGER,
  TEMPO_TOTAL_TD               INTEGER,
  TEMPO_TOTAL_FORMATADO_TD     VARCHAR(20) CHARACTER SET UTF8,
  CONSTRAINT PK_METRICAS_TICK_DIFF PRIMARY KEY (AUTOINC_METRICA_TICK_DIFF_TD),
  CONSTRAINT FK_METRICAS_TICK_HISTORICO FOREIGN KEY (AUTOINC_HISTORICO_HE)
    REFERENCES HISTORICO_EXECUCAO (AUTOINC_HISTORICO_HE)
);

CREATE TABLE METRICAS_ASSERTS (
  AUTOINC_METRICA_ASSERTS_AT INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  AUTOINC_HISTORICO_HE       INTEGER NOT NULL,
  ETAPA_CASO_TESTE_AT        INTEGER,
  TEMPO_TOTAL_AT             INTEGER,
  ASSERTS_TOTAL_AT           INTEGER,
  ASSERTS_APROVADOS_AT       INTEGER,
  ASSERTS_FALHOS_AT          INTEGER,
  RESULTADO_ESPERADO_AT      BLOB SUB_TYPE 1 SEGMENT SIZE 100 CHARACTER SET UTF8,
  RESULTADO_OBTIDO_AT        BLOB SUB_TYPE 1 SEGMENT SIZE 100 CHARACTER SET UTF8,
  CONSTRAINT PK_METRICAS_ASSERTS PRIMARY KEY (AUTOINC_METRICA_ASSERTS_AT),
  CONSTRAINT FK_METRICAS_ASSERTS_HISTORICO FOREIGN KEY (AUTOINC_HISTORICO_HE)
    REFERENCES HISTORICO_EXECUCAO (AUTOINC_HISTORICO_HE)
);

CREATE INDEX IDX_HISTORICO_EXECUCAO_CASO ON HISTORICO_EXECUCAO (AUTOINC_CASO_TESTE_HE);
CREATE INDEX IDX_METRICAS_TICK_HISTORICO ON METRICAS_TICK_DIFF (AUTOINC_HISTORICO_HE);
CREATE INDEX IDX_METRICAS_ASSERTS_HISTORICO ON METRICAS_ASSERTS (AUTOINC_HISTORICO_HE);
COMMIT WORK;
